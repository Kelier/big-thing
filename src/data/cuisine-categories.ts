/** 拉绳模式（roll）的四个子模式 + 地图模式（explore） */
export type AppMode = "eat" | "drink" | "toilet" | "sleep" | "explore";
export const ROLL_MODES = ["eat", "drink", "toilet", "sleep"] as const;
export type RollMode = (typeof ROLL_MODES)[number];
export const isRollMode = (m: AppMode): m is RollMode => m !== "explore";

export type Place = {
  id: string;
  name: string;
  area: string;
  distanceM: number;
  /** 人均 / 门票，单位：元；真实数据里很多地点没有价格，为 null */
  price: number | null;
  signature: string;
  lat?: number;
  lng?: number;
  /** 真实数据自带的导航链接；示例数据没有 */
  navUrl?: string;
};

export type Category = {
  id: string;
  name: string;
  en: string;
  /** 揭晓时页面背景的淡染色 */
  tint: string;
  quip: string;
  places: Place[];
};

type P = [name: string, area: string, distanceM: number, price: number, signature: string];

const build = (
  id: string,
  name: string,
  en: string,
  tint: string,
  quip: string,
  places: P[],
): Category => ({
  id,
  name,
  en,
  tint,
  quip,
  places: places.map(([n, area, distanceM, price, signature], i) => ({
    id: `${id}-${i}`,
    name: n,
    area,
    distanceM,
    price,
    signature,
  })),
});

